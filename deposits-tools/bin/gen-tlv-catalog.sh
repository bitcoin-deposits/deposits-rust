#!/bin/bash
# Generate wallet/tlv-catalog.js from deposits_protocol.ksy
#
# Extracts OP_NAMES (discriminant -> name) and FIELD_NAMES (field type -> name)
# from the Kaitai Struct spec so the wallet UI stays in sync.
#
# Usage: ./bin/gen-tlv-catalog.sh

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
KSY="$SCRIPT_DIR/../../deposits-protocol/deposits_protocol.ksy"
OUTPUT="$SCRIPT_DIR/../wallet/tlv-catalog.js"

if [ ! -f "$KSY" ]; then
    echo "Error: $KSY not found" >&2
    exit 1
fi

{
echo "// AUTO-GENERATED by bin/gen-tlv-catalog.sh -- do not edit manually"
echo "// Source: deposits-protocol/deposits_protocol.ksy"
echo ""

# --- OP_NAMES: "  1  = LedgerOpen" lines in Discriminant values block ---
echo "export const OP_NAMES = {"
sed -n '/Discriminant values:/,/^    seq:/p' "$KSY" | \
    grep -E '^ +[0-9]+ += +[A-Z]' | \
    sed -E "s/^ +([0-9]+) += +([A-Za-z]+).*/  \1: '\2',/" | \
    sort -t: -k1 -n
echo "};"
echo ""

# --- FIELD_NAMES: "#   2   = amount (u64, msats)" lines ---
# Skip entries whose name is "reserved" (marker for removed TLV types) — they
# shouldn't appear in the catalog the wallet uses for display.
echo "export const FIELD_NAMES = {"
sed -n '/TLV field type reference/,/^  [a-z]/p' "$KSY" | \
    grep -E '^ *# +[0-9]+ += +[a-z]' | \
    sed -E "s/^ *# +([0-9]+) += +([a-z_]+).*/\1 \2/" | \
    grep -v ' reserved$' | \
    sort -n -u | \
    while read num name; do
        echo "  ${num}: '${name}',"
    done
echo "};"

} > "$OUTPUT"

echo "Generated $OUTPUT ($(grep -c ":" "$OUTPUT") entries)"
